function orientation = rotationMatrixToQuaternion(frame)
% Convert a local-to-world rotation matrix to [x; y; z; w].
traceValue = trace(frame);
if traceValue > 0
    scale = sqrt(traceValue + 1) * 2;
    orientation = [(frame(3, 2) - frame(2, 3)) / scale; ...
                   (frame(1, 3) - frame(3, 1)) / scale; ...
                   (frame(2, 1) - frame(1, 2)) / scale; ...
                   0.25 * scale];
elseif frame(1, 1) > frame(2, 2) && frame(1, 1) > frame(3, 3)
    scale = sqrt(1 + frame(1, 1) - frame(2, 2) - frame(3, 3)) * 2;
    orientation = [0.25 * scale; ...
                   (frame(1, 2) + frame(2, 1)) / scale; ...
                   (frame(1, 3) + frame(3, 1)) / scale; ...
                   (frame(3, 2) - frame(2, 3)) / scale];
elseif frame(2, 2) > frame(3, 3)
    scale = sqrt(1 + frame(2, 2) - frame(1, 1) - frame(3, 3)) * 2;
    orientation = [(frame(1, 2) + frame(2, 1)) / scale; ...
                   0.25 * scale; ...
                   (frame(2, 3) + frame(3, 2)) / scale; ...
                   (frame(1, 3) - frame(3, 1)) / scale];
else
    scale = sqrt(1 + frame(3, 3) - frame(1, 1) - frame(2, 2)) * 2;
    orientation = [(frame(1, 3) + frame(3, 1)) / scale; ...
                   (frame(2, 3) + frame(3, 2)) / scale; ...
                   0.25 * scale; ...
                   (frame(2, 1) - frame(1, 2)) / scale];
end
orientation = single(orientation / norm(orientation));
end
